// 随机中文昵称
export function generateRandomNickname() {
  const adjectives = [
    '快乐', '聪明', '勇敢', '可爱', '温柔', '活泼', '机灵', '善良',
    '热情', '幽默', '诚实', '乐观', '坚强', '开朗', '细心', '大方'
  ];

  const animals = [
    '小熊', '小兔', '小猫', '小狐狸', '小熊猫', '小鹿', '小虎', '小狼',
    '小鸟', '小鱼', '小蛇', '小羊', '小鸡', '小鸭', '小猪', '小狗',
    '小马', '小牛', '小猴', '小象', '小狮', '小龙', '小兔', '小豚'
  ];

  const randomAdjective = adjectives[Math.floor(Math.random() * adjectives.length)];
  const randomAnimal = animals[Math.floor(Math.random() * animals.length)];

  return randomAdjective + randomAnimal;
}

// 随机获取不重复的SVG头像
export function getRandomAvatar(excludedIds = []) {
  const availableAvatars = CARTOON_AVATARS.filter(av => !excludedIds.includes(av.id));

  if (availableAvatars.length === 0) {
    // 如果所有头像都被使用，重置并返回第一个
    return CARTOON_AVATARS[0];
  }

  const randomIndex = Math.floor(Math.random() * availableAvatars.length);
  return availableAvatars[randomIndex];
}

// 将SVG转换为data URL
export function svgToDataUrl(svg) {
  const blob = new Blob([svg], { type: 'image/svg+xml' });
  return URL.createObjectURL(blob);
}
